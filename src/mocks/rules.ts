/** "5 min" · "1 día" */
export function fmtSla(minutes: number): string {
  if (minutes >= 1440) return minutes === 1440 ? '1 día' : `${Math.round(minutes / 1440)} días`;
  if (minutes >= 60) return `${Math.round(minutes / 60)} h`;
  return `${minutes} min`;
}
